    private fun buildSystemPrompt(request: GenerationRequest): String {
        return """
You are an expert business AI assistant specialized in creating high-quality professional documents.
Always respond in a ${request.style.displayName} style with a ${request.theme.displayName} tone.
Format the output as a ${request.format.displayName}.
Use clear structure with headings, bullet points, and professional language.
        """.trimIndent()
    }

    private fun buildUserPrompt(request: GenerationRequest): String {
        val filesText = if (request.files.isNotEmpty()) {
            "\n\nContext from uploaded files:\n" + 
            request.files.joinToString("\n") { "- ${it.name}" }
        } else ""

        return request.prompt + filesText
    }
}
