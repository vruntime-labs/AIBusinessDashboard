import java.util.UUID

/**
 * AI Service - Supports both Mock mode and Real API mode.
 * 
 * To use real AI:
 * 1. Set your API key in Preferences / Settings
 * 2. Toggle "Use Real AI" in the generation screen
 * 
 * Currently structured for OpenAI-compatible APIs (OpenAI, Grok, etc.)
 */
class AIService {

    // Change this base URL for different providers
    // OpenAI: https://api.openai.com/v1/
    // Grok (xAI): https://api.x.ai/v1/
    private val baseUrl = "https://api.openai.com/v1/"

    suspend fun generate(request: GenerationRequest, apiKey: String? = null): GenerationResult {
        return if (request.useRealAI && !apiKey.isNullOrBlank()) {
            generateWithRealAPI(request, apiKey)
        } else {
            generateMock(request)
        }
    }

    private suspend fun generateMock(request: GenerationRequest): GenerationResult {
        // Simulate network delay
        delay(1800)

        val content = when (request.type) {
            GenerationType.TEXT -> buildMockTextResponse(request)
            GenerationType.IMAGE -> "Image generation placeholder. In real mode this would return an image URL."
        }

        return GenerationResult(
            id = UUID.randomUUID().toString(),
            request = request,
            content = content,
            imageUrl = if (request.type == GenerationType.IMAGE) 
                "https://picsum.photos/seed/${System.currentTimeMillis()}/800/600" else null,
            isSuccess = true
        )
    }

    private fun buildMockTextResponse(request: GenerationRequest): String {
        val formatName = request.format.displayName
        val styleName = request.style.displayName
        val themeName = request.theme.displayName
        val filesInfo = if (request.files.isNotEmpty()) {
            "\n\n**Attached Files:**\n" + request.files.joinToString("\n") { "- ${it.name}" }
        } else ""

        return """
# $formatName

**Style:** $styleName  
**Theme:** $themeName  
**Generated for:** Business Professional Use

---

## Executive Overview

Based on your request:  
"${request.prompt}"

$filesInfo

This is a **professionally generated** $formatName written in a **$styleName** style with a **$themeName** tone.

### Key Points

1. **Strategic Alignment**  
   The content has been structured to align with modern corporate communication standards.

2. **Clarity & Precision**  
   Language is clear, concise, and suitable for executive stakeholders.

3. **Actionable Insights**  
   Recommendations are practical and ready for implementation.

### Detailed Content

Lorem ipsum business content would appear here in a real AI response.  
In production, this section is replaced by the actual AI model output (GPT-4o, Grok, Claude, etc.).

### Recommendations

- Review the generated content carefully
- Customize key sections according to your specific needs
- Export in your preferred format (PDF / Markdown / Text)

---

*Generated by AI Business Dashboard • Mock Mode*  
*Toggle "Use Real AI" in settings and add your API key for live generation.*
        """.trimIndent()
    }

